"""The forge C-Star application: wires ``ForgeBlueprint`` into a real,
C-Star-discoverable application via :class:`ForgeRunner` + :class:`ForgeApplication`
(see ``cstar.orchestration.models.Blueprint`` /
https://c-star.readthedocs.io/en/latest/custom_applications.html).

Not part of the "forge application" boundary that ``tests/test_forge_app_boundary.py``
guards -- like ``runtime.py``, this module is **host-resolution glue**: it reaches
into ``cstar.applications.forge.config`` (via ``cstar.applications.forge.runtime.process``)
to resolve the host, which the guarded ``cstar.applications.forge`` modules that
implement blueprint processing itself must never do.

Discovered by ``cstar.applications.core.get_application`` as a built-in application,
the same way ``roms_marbl`` is: ``get_application`` imports the in-tree
``cstar.applications.forge`` package, whose ``__init__.py`` imports this module so its
:func:`register_application` decorator runs. No entry point or environment variable is
involved.

Scope (2026-07, first cut): :meth:`ForgeRunner.run` generates ROMS-MARBL inputs and
emits the downstream ``roms_marbl`` blueprint (``B_{name}.yaml``), then stops -- it
does not chain into actually running the ROMS-MARBL simulation. That is the existing
``roms_marbl`` application's job, consuming the blueprint forge just produced. See
``docs/developers/forge_internals.rst`` for the producer/consumer boundary between the two
applications.
"""

from __future__ import annotations

import fnmatch
import glob
import typing as t
from pathlib import Path

from cstar.applications.core import (
    ApplicationDefinition,
    ArtifactKind,
    ArtifactSpec,
    EmittedBlueprint,
    RunnerResult,
    register_application,
)
from cstar.applications.forge.blueprint import (
    DEFAULT_APPLICATION,
    ForgeBlueprint,
    emitted_blueprint_filename,
    producer_ref,
)
from cstar.entrypoint.runner import BlueprintRunner
from cstar.execution.file_system import JobFileSystemManager
from cstar.execution.handler import ExecutionStatus
from cstar.orchestration.manifest import Product

if t.TYPE_CHECKING:
    from collections.abc import Sequence

    from cstar.applications.forge.executor import ForgeExecutor

APP_NAME: t.Final[str] = DEFAULT_APPLICATION

_APP_NAME_LONG: t.Final[str] = "C-Star Forge domain generator"

INPUT_ARTIFACTS: t.Final[tuple[tuple[str, ArtifactKind, dict[str, str]], ...]] = (
    ("grid", ArtifactKind.grid, {}),
    ("grid_child", ArtifactKind.grid, {"role": "child"}),
    ("nesting", ArtifactKind.grid, {"role": "nesting"}),
    ("initial_conditions", ArtifactKind.initial_conditions, {}),
    ("boundary-*", ArtifactKind.boundary_forcing, {}),
    ("surface-*", ArtifactKind.surface_forcing, {}),
    ("tidal", ArtifactKind.tidal_forcing, {}),
    ("river", ArtifactKind.river_forcing, {}),
    ("cdr", ArtifactKind.cdr_forcing, {}),
)
"""The stem of each generated input NetCDF (`input_data/<domain>_<stem>.nc`), as
`fnmatch` globs in precedence order, with its kind and starting metadata. The `cdr`
stem is `input_data.CDR_FORCING_NETCDF_STEM`, spelled out here because importing
that module is too heavy for registration."""


def input_products(executor: ForgeExecutor) -> list[Product]:
    """Describe the input NetCDF files a forge run generated by stem.

    Only classifies by file name (`INPUT_ARTIFACTS`): the declared patterns own
    each file's size.

    Parameters
    ----------
    executor : ForgeExecutor
        The executor that generated the inputs.

    Returns
    -------
    list[Product]
        One product per planned input file that exists and has a known stem, in
        planned order. The metadata of one with a sidecar blueprint names it.
    """
    # Deferred: this package's import (registration) must stay light.
    from cstar.applications.forge.executor import BLUEPRINTS_DIR_NAME
    from cstar.applications.forge.input_data import netcdf_filename_component

    root = executor.run_output_dir.resolve()
    prefix = f"{netcdf_filename_component(executor.name)}_"
    products: list[Product] = []
    # the planned list is the one exact list of the files the run generates
    for path in executor._planned_netcdf_outputs():
        if not path.is_file() or not path.stem.startswith(prefix):
            continue
        stem = path.stem.removeprefix(prefix)
        row = next(
            (row for row in INPUT_ARTIFACTS if fnmatch.fnmatchcase(stem, row[0])),
            None,
        )
        if row is None:
            continue
        _, kind, base_metadata = row
        metadata: dict[str, str | int | float | list[str]] = dict(base_metadata)
        sidecar = Path(BLUEPRINTS_DIR_NAME) / f"_{stem}.yaml"
        if (root / sidecar).is_file():
            metadata["sidecar"] = sidecar.as_posix()
        products.append(
            Product(
                kind=kind.value,
                path=path.relative_to(root).as_posix(),
                metadata=metadata,
            )
        )
    return products


class ForgeRunner(BlueprintRunner[ForgeBlueprint]):
    """Worker class that runs the forge domain-generation pipeline from a blueprint."""

    @t.override
    async def run(self) -> RunnerResult[ForgeBlueprint]:
        """Generate ROMS-MARBL inputs and emit the downstream ``roms_marbl`` blueprint.

        Delegates to ``cstar.applications.forge.runtime.process`` (host-resolution glue) ->
        ``forge_blueprint_engine.process_forge_blueprint`` -> the ``ForgeExecutor``
        substitution seam (``ensure_source_data`` -> ``generate_inputs`` ->
        ``configure_build``). Synchronous and heavy (network fetches, roms-tools
        NetCDF generation), and deliberately run inline on the event loop rather
        than via ``asyncio.to_thread``. ``Service`` handles SIGINT/SIGTERM with plain
        ``signal.signal`` handlers that do their bookkeeping and *return*, so the
        first signal restores the default handlers and the second raises
        ``KeyboardInterrupt`` on the main thread. Inline, that interrupt lands in
        forge's own frames and unwinds the run; on a worker thread it would land in
        the idle event loop instead, and ``asyncio.run`` would then join the
        un-cancellable worker on exit, leaving the process running until the current
        NetCDF write finished. Nothing else needs the loop free while forge works:
        the healthcheck is its own thread and ``execute`` awaits iterations
        sequentially. (Forge's dask/BLAS/numba thread caps and the xarray lock
        patch are process-global or scoped to the calling thread, so they were not
        the constraint.)

        Returns
        -------
        RunnerResult
            The result of the blueprint processing.
        """
        from cstar.applications.forge import runtime as forge_run

        try:
            executor = forge_run.process(self.blueprint)
        except Exception as ex:
            msg = "An error occurred while generating forge inputs"
            self.log.exception(msg)
            self.add_state(ExecutionStatus.FAILED, [msg, str(ex)])
            return self.result

        self.log.debug(
            f"Forge blueprint emitted: {executor.path_roms_marbl_blueprint()}"
        )
        # reporting never changes the outcome: the declared patterns still
        # list the files at shutdown, without the sidecar metadata
        try:
            self.products.extend(input_products(executor))
        except Exception as ex:
            self.log.warning(f"Unable to describe the generated inputs: {ex}")
        published = forge_run.publish_emitted_blueprint(executor)
        self.log.info(f"Forge blueprint published for downstream steps: {published}")
        self.add_state(ExecutionStatus.COMPLETED)
        return self.result


@register_application
class ForgeApplication(ApplicationDefinition[ForgeBlueprint, ForgeRunner]):
    """Registers ``forge`` with C-Star's application registry (see the module
    docstring for how the ``cstar.applications`` entry point reaches this module).
    """

    name = APP_NAME
    long_name = _APP_NAME_LONG
    runner = ForgeRunner
    blueprint = ForgeBlueprint
    applicable_transforms = ()
    migrations = ()

    @t.override
    def emitted_blueprint(self, blueprint: ForgeBlueprint) -> EmittedBlueprint:
        """Describe the `roms_marbl` blueprint a forge run of `blueprint` publishes.

        Parameters
        ----------
        blueprint : ForgeBlueprint
            The blueprint of the forge step.

        Returns
        -------
        EmittedBlueprint
            The predicted `roms_marbl` blueprint.
        """
        # Deferred: this package's import (registration) must stay light, and
        # these pull in roms_tools/xarray/dask.
        from cstar.applications.forge.input_data import netcdf_basename
        from cstar.applications.roms_marbl.models import APP_NAME as ROMS_MARBL_APP

        return EmittedBlueprint(
            filename=emitted_blueprint_filename(blueprint.name),
            application=ROMS_MARBL_APP,
            producer=producer_ref(blueprint),
            cpus_needed=blueprint.n_procs,
            single_node=False,
            start_date=blueprint.run.start_date,
            end_date=blueprint.run.end_date,
            use_pio=blueprint.use_pio,
            grid_filename=netcdf_basename(blueprint.name, "grid"),
        )

    @t.override
    def artifacts(self, blueprint: ForgeBlueprint) -> Sequence[ArtifactSpec]:
        """Declare the files a forge run leaves in its step root.

        Parameters
        ----------
        blueprint : ForgeBlueprint
            The blueprint of the forge step.

        Returns
        -------
        Sequence[ArtifactSpec]
            The published `roms_marbl` blueprint, the generated input NetCDF files,
            the rendered build configuration and the run log.
        """
        # Deferred like `emitted_blueprint`: these pull in roms_tools/xarray/dask.
        from cstar.applications.forge.executor import (
            BUILDS_DIR_NAME,
            COMPILE_TIME_DIR_NAME,
            INPUT_DATA_DIR_NAME,
            RUN_TIME_DIR_NAME,
        )
        from cstar.applications.forge.input_data import netcdf_filename_component

        fs = JobFileSystemManager(Path("/"))
        output = fs.output_dir.relative_to(fs.root_dir)
        logs = fs.logs_dir.relative_to(fs.root_dir)
        domain = glob.escape(netcdf_filename_component(blueprint.name))
        builds = Path(BUILDS_DIR_NAME)

        inputs = [
            ArtifactSpec(
                kind=kind,
                pattern=f"{INPUT_DATA_DIR_NAME}/{domain}_{stem}.nc",
                metadata=dict(metadata),
            )
            for stem, kind, metadata in INPUT_ARTIFACTS
        ]
        return [
            ArtifactSpec(
                kind=ArtifactKind.emitted_blueprint,
                pattern=(
                    output / glob.escape(emitted_blueprint_filename(blueprint.name))
                ).as_posix(),
            ),
            *inputs,
            ArtifactSpec(
                kind=ArtifactKind.config,
                pattern=(builds / COMPILE_TIME_DIR_NAME / "cppdefs.opt").as_posix(),
                metadata={"role": "cppdefs"},
            ),
            ArtifactSpec(
                kind=ArtifactKind.config,
                pattern=(builds / RUN_TIME_DIR_NAME / "namelist.nml").as_posix(),
                metadata={"role": "namelist"},
            ),
            ArtifactSpec(
                kind=ArtifactKind.config,
                pattern=(builds / RUN_TIME_DIR_NAME / "marbl_in").as_posix(),
                metadata={"role": "marbl_in"},
            ),
            ArtifactSpec(
                kind=ArtifactKind.log, pattern=(logs / "forge_*.log").as_posix()
            ),
        ]

log = get_logger(__name__)
app = typer.Typer()

COMMAND_CHECK: t.Final[str] = "check"
"""Name of the command that checks a run directory."""

KEY_TARGET: t.Final[str] = "check_target"
"""Context-map key under which the resolved target is stored."""

WORKPLAN_FILE_SUFFIXES: t.Final[frozenset[str]] = frozenset({".yaml", ".yml"})
"""Suffixes that identify a workplan file, which `cstar workplan check` validates."""

HELP_SHORT = "Check that a run directory still works when it is moved."
HELP_LONG = f"""\
{HELP_SHORT}

The target is a run-id, or the path of a run directory (one that contains
`tasks/`). The run's emitted files are searched for absolute paths under the
run or the C-Star data home, its symlinks for absolute or missing targets, and
its transformed workplan for steps without a directory. Files that launchers
regenerate are skipped unless {ARG_ALL} is given. Steps that have not started
have no directory yet.

Task directories and sentinel files that no step accounts for, and symlinks to
an absolute path outside the run, are listed for information and do not fail
the check. Nothing is deleted.

{ARG_REPAIR} rewrites each absolute symlink that points inside the run as a
relative one and rebuilds `gathered_output` if the run has one. It changes
nothing else: files that name absolute paths are regenerated by running the
workplan again.

To validate a workplan file, use `cstar workplan check <file>` instead.

Exit code 0: nothing to fix. 1: findings remain. 2: bad arguments.
"""

_HEADINGS: t.Final[dict[FindingKind, str]] = {
    FindingKind.ABSOLUTE_PATH: "Absolute paths in run files",
    FindingKind.ABSOLUTE_LINK: f"Symlinks with an absolute target inside the run (fixed by {ARG_REPAIR})",
    FindingKind.DANGLING_LINK: "Symlinks whose target does not exist",
    FindingKind.MISSING_STEP_DIR: "Steps without a directory",
    FindingKind.EXTERNAL_LINK: "Symlinks with an absolute target outside the run (informational)",
}
"""The heading of each kind of finding, in the order the kinds are listed."""


@dataclass(frozen=True)
class CheckTarget:
    """What the `target` argument resolved to."""

    run_root: Path
    """The run directory to check."""
    run_id: str | None
    """The run-id, when the target was found through tracking."""
    workplan_path: Path | None
    """The transformed workplan, when one is known."""


def refuse_workplan_file(_context: typer.Context, target: str) -> str:
    """Refuse a workplan file: this command checks a run, not a workplan.

    Parameters
    ----------
    _context : typer.Context
        The typer context (unused).
    target : str
        The user-supplied target.

    Returns
    -------
    str

    Raises
    ------
    typer.BadParameter
        Raised when the target names a YAML file.
    """
    if Path(target).suffix.casefold() in WORKPLAN_FILE_SUFFIXES:
        msg = (
            f"{target!r} is a workplan file, not a run. "
            f"To validate it, use `cstar workplan check {target}`."
        )
        raise typer.BadParameter(msg)

    return target


def _is_path(target: str) -> bool:
    """Whether a target is spelled as a path rather than as a run-id.

    A run-id is a slug, so it never holds a path separator or starts with a dot
    or a tilde.

    Parameters
    ----------
    target : str
        The user-supplied target.

    Returns
    -------
    bool
    """
    return os.sep in target or target.startswith((".", "~"))


def _directory_target(target: str) -> CheckTarget:
    """Resolve a target spelled as the path of a run directory.

    Parameters
    ----------
    target : str
        The user-supplied path.

    Returns
    -------
    CheckTarget

    Raises
    ------
    typer.BadParameter
        - Raised when the path is not a directory containing `tasks/`.
        - Raised when the directory holds more than one transformed workplan.
    """
    run_root = Path(os.path.abspath(Path(target).expanduser()))
    if not run_root.is_dir():
        raise typer.BadParameter(f"{str(run_root)!r} is not a directory.")
    if not (run_root / "tasks").is_dir():
        msg = f"{str(run_root)!r} is not a run directory: it has no `tasks` directory."
        raise typer.BadParameter(msg)

    workplans = sorted(run_root.glob(TRANSFORMED_WORKPLAN_GLOB))
    if len(workplans) > 1:
        names = ", ".join(p.name for p in workplans)
        msg = (
            f"{str(run_root)!r} holds more than one transformed workplan ({names}); "
            "remove the stale ones."
        )
        raise typer.BadParameter(msg)

    return CheckTarget(run_root, None, next(iter(workplans), None))


def _run_target(context: typer.Context, target: str) -> CheckTarget:
    """Resolve a target spelled as a run-id through tracking.

    Parameters
    ----------
    context : typer.Context
        The typer context; receives the run record from `preload_run_record`.
    target : str
        The user-supplied run-id.

    Returns
    -------
    CheckTarget

    Raises
    ------
    typer.BadParameter
        - Raised when no run is tracked under the run-id.
        - Raised when the run's recorded directory does not exist.
    """
    try:
        preload_run_record(context, target)
    except typer.BadParameter as ex:
        if Path(target).is_dir():
            msg = f"{ex.message} To check the directory ./{target}, pass it as a path."
            raise typer.BadParameter(msg) from ex
        raise

    run = get_from_ctxmap(context, "run", WorkplanRun)
    if not run.output_path.is_dir():
        msg = (
            f"The directory recorded for run {run.run_id!r} does not exist: "
            f"{run.output_path}. To check a moved run, pass its directory as a path."
        )
        raise typer.BadParameter(msg)

    return CheckTarget(run.output_path, run.run_id, run.trx_workplan_path)


def resolve_target(context: typer.Context, target: str) -> str:
    """Resolve the target to a run directory and store it in the context map.

    Parameters
    ----------
    context : typer.Context
        The typer context.
    target : str
        The user-supplied run-id or directory path.

    Returns
    -------
    str
        The target, unchanged.

    Raises
    ------
    typer.BadParameter
        Raised when the target does not identify a run directory.
    """
    resolved = (
        _directory_target(target) if _is_path(target) else _run_target(context, target)
    )
    set_ctxmap(context, KEY_TARGET, resolved)
    return target


def _format_findings(report: RunCheckReport) -> "Iterator[str]":
    """Format the report: a heading and one line per finding, kind by kind.

    Parameters
    ----------
    report : RunCheckReport
        The report to format.

    Yields
    ------
    str
    """
    for kind, heading in _HEADINGS.items():
        if found := [f for f in report.findings if f.kind is kind]:
            yield f"{heading} ({len(found)}):"
            for f in found:
                if kind is FindingKind.ABSOLUTE_PATH:
                    yield f"  {f.file}:{f.line}: {f.path}"
                elif kind is FindingKind.MISSING_STEP_DIR:
                    yield f"  {f.file}"
                else:
                    yield f"  {f.file} -> {f.path}"

    if report.orphans.step_dirs:
        yield f"Step directories no step accounts for (informational) ({len(report.orphans.step_dirs)}):"
        yield from (f"  {p}" for p in report.orphans.step_dirs)
    if report.orphans.sentinels:
        yield f"Sentinel files no step accounts for (informational) ({len(report.orphans.sentinels)}):"
        yield from (f"  {p}" for p in report.orphans.sentinels)

    yield from (f"Skipped {reason}" for reason in report.skipped)


def _summary(report: RunCheckReport) -> str:
    """Summarize the report in one line.

    Parameters
    ----------
    report : RunCheckReport
        The report to summarize.

    Returns
    -------
    str
    """
    informational = len(report.findings) - len(report.problems)
    informational += len(report.orphans.step_dirs) + len(report.orphans.sentinels)
    extra = f", {informational} informational" if informational else ""

    if report.clean:
        return f"No problems found in {report.run_root}{extra}."
    return f"{len(report.problems)} problem(s) found in {report.run_root}{extra}."


def _regather(run_root: Path, workplan: LiveWorkplan | None) -> None:
    """Rebuild the run's `gathered_output` directory when it has one.

    The rebuild is skipped, with a message, when there is no transformed
    workplan or it does not point at this run directory: gather would have no
    steps to link, or would link into the original location.

    Parameters
    ----------
    run_root : Path
        The run directory.
    workplan : LiveWorkplan | None
        The run's transformed workplan, when it could be loaded.

    Raises
    ------
    typer.Exit
        With code 1 when a link name collides, or the directory holds real files.
    """
    # gather links to resolved step directories, so the links are relative to the
    # resolved directory too, whichever way the run was reached
    dest = gathered_output_dir(run_root.resolve())
    if not dest.is_dir():
        return

    if workplan is None:
        reason = "no transformed workplan could be loaded"
    elif not steps_inside_run(run_root, workplan):
        reason = "the transformed workplan describes a different directory"
    else:
        links, conflicts, _ = collect_links(workplan)
        if conflicts:
            report_conflicts(conflicts)
            raise typer.Exit(1)

        relink(dest, links)
        typer.echo(f"Rebuilt {dest} with {len(links)} link(s).")
        return

    typer.echo(
        f"Did not rebuild {dest}: {reason}. "
        "Run `cstar run gather <run-id>` from the run's original location."
    )


@app.command(name=COMMAND_CHECK, help=HELP_LONG, short_help=HELP_SHORT)
def check(
    context: typer.Context,
    target: t.Annotated[
        str,
        typer.Argument(
            help="A run-id, or the path of a run directory.",
            autocompletion=list_runs,
            callback=cb_pipeline(refuse_workplan_file, resolve_target),
        ),
    ],
    repair: t.Annotated[bool, typer.Option(ARG_REPAIR, help=ARG_REPAIR_HELP)] = False,
    all_files: t.Annotated[bool, typer.Option(ARG_ALL, help=ARG_ALL_HELP)] = False,
) -> None:
    """Check that a run directory still works when it is moved."""
    resolved = get_from_ctxmap(context, KEY_TARGET, CheckTarget)
    run_root = resolved.run_root

    workplan = None
    if resolved.workplan_path is not None:
        workplan = try_deserialize(resolved.workplan_path, LiveWorkplan)
        if workplan is None:
            msg = f"Warning: unable to load the transformed workplan {resolved.workplan_path}"
            typer.echo(msg, err=True)

    def run_checks() -> RunCheckReport:
        return check_run(
            run_root, workplan=workplan, run_id=resolved.run_id, all_files=all_files
        )

    report = run_checks()
    if repair:
        repaired = repair_symlinks(run_root)
        if repaired:
            typer.echo(f"Rewrote {len(repaired)} symlink(s) as relative:")
            for link in repaired:
                typer.echo(f"  {link} -> {os.readlink(link)}")
            report = run_checks()
        else:
            typer.echo("No symlink to rewrite.")

    for line in _format_findings(report):
        typer.echo(line)
    typer.echo(_summary(report))

    if repair:
        _regather(run_root, workplan)

    if not report.clean:
        raise typer.Exit(1)


if __name__ == "__main__":
    app()

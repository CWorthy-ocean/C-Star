log = get_logger(__name__)

REFERENCE_FILES: t.Final[tuple[str, ...]] = (
    "output/*.yaml",
    "blueprints/B_*.yaml",
    "work/cstar_generated_roms.nml",
)
"""Globs, relative to a step directory, of the emitted files that refer to other files."""

LAUNCH_FILES: t.Final[tuple[str, ...]] = (
    "work/*.ovrd*.yaml",
    "work/directives.yaml",
    "script.sh",
    "builds/run-time/namelist.nml",
    "input/runtime_code/namelist.nml",
)
"""Globs, relative to a step directory, of the files a launcher regenerates at launch."""

_PATH_CHARS_AFTER: t.Final[str] = r"""[^\s'"`,;<>()\[\]{}]*"""
"""The characters that continue a path once its leading prefix has matched."""


class FindingKind(StrEnum):
    """The ways a run directory can fail to be self-contained."""

    ABSOLUTE_PATH = auto()
    """An emitted file names an absolute path under the data home, outside the run."""
    RUN_PATH = auto()
    """An emitted file names an absolute path inside the run (see `is_run_path`)."""
    ABSOLUTE_LINK = auto()
    """A symlink has an absolute target inside the run; `repair_symlinks` rewrites it."""
    EXTERNAL_LINK = auto()
    """A symlink targets a place outside the run, by absolute or climbing relative path."""
    DANGLING_LINK = auto()
    """A symlink's target does not exist."""
    CODEBASE_LINK = auto()
    """A symlink inside a step's cloned codebases has no target: the codebase's
    repository commits it (ucla-roms holds a libtool link to a library C-Star
    never builds)."""
    MISSING_STEP_DIR = auto()
    """A step of the transformed workplan has no `tasks/<slug>` directory."""
    PRODUCT_MISSING = auto()
    """A product the step record lists is not in the run."""
    PRODUCT_SIZE = auto()
    """A product's size differs from the one its step record lists."""
    DIGEST_MISMATCH = auto()
    """A product's content differs from the digest its step record lists, or cannot be read to compare (`--verify`)."""
    INPUT_MISMATCH = auto()
    """A file an attempt carried differs from the digest the manifest records for it."""
    RECORD_MISSING = auto()
    """A step the manifest says is done has no step record."""
    ATTEMPT_OPEN = auto()
    """The latest attempt has not finished: the run is unfinished, or was copied before it was."""
    INPUT_MISSING = auto()
    """An attempt's directory, or a file it carried, is not in the run; older attempts may be deleted by hand."""

    @property
    def informational(self) -> bool:
        """Whether the finding is reported without making the run fail the check."""
        return self in {
            FindingKind.RUN_PATH,
            FindingKind.CODEBASE_LINK,
            FindingKind.EXTERNAL_LINK,
            FindingKind.RECORD_MISSING,
            FindingKind.ATTEMPT_OPEN,
            FindingKind.INPUT_MISSING,
        }


@dataclass(frozen=True)
class Finding:
    """One place where a run directory is not self-contained."""

    kind: FindingKind
    """What is wrong."""
    file: Path
    """The file, symlink or (for a missing step) directory the finding is about."""
    line: int | None = None
    """The 1-based line of `file` holding `path`, for a finding in a text file."""
    path: str = ""
    """The offending path text: the absolute path found, or the target of a link."""


@dataclass(frozen=True)
class Orphans:
    """Leftovers that no step of the transformed workplan accounts for."""

    step_dirs: tuple[Path, ...] = ()
    """Entries of the run's `tasks` directory that no step works in or beneath."""
    sentinels: tuple[Path, ...] = ()
    """Sentinel files of the run that match no step's expected sentinel name."""

    def __bool__(self) -> bool:
        """Whether any leftover exists."""
        return bool(self.step_dirs or self.sentinels)


@dataclass
class DigestTally:
    """What comparing the products with their recorded digests found, product by product."""

    matched: int = 0
    """Products whose content matches the recorded digest."""
    differed: int = 0
    """Products whose content differs from the recorded digest, or cannot be read."""
    no_digest: int = 0
    """Products recorded without a digest."""
    foreign: dict[str, int] = field(default_factory=dict)
    """Products recorded with a scheme this build does not compute, by scheme."""
    not_compared: int = 0
    """Products missing, resized or not a regular file: the first two are findings."""

    @property
    def compared(self) -> int:
        """The products whose content was compared with their recorded digest."""
        return self.matched + self.differed


@dataclass(frozen=True)
class RunCheckReport:
    """Everything `check_run` found in a run directory."""

    run_root: Path
    """The resolved run directory that was checked."""
    findings: tuple[Finding, ...] = ()
    """The findings, ordered by kind, then file, then line."""
    orphans: Orphans = field(default_factory=Orphans)
    """The leftovers no step accounts for; informational."""
    skipped: tuple[str, ...] = ()
    """Why each check that could not run was skipped."""
    verification: DigestTally | None = None
    """What the digest comparison found; `None` unless it was asked for and the
    run has a manifest."""

    @property
    def problems(self) -> tuple[Finding, ...]:
        """The findings that make the run fail the check."""
        return tuple(f for f in self.findings if not f.kind.informational)

    @property
    def clean(self) -> bool:
        """Whether the run has no finding that fails the check."""
        return not self.problems


def gathered_output_dir(run_root: Path) -> Path:
    """The directory `cstar run gather` builds inside a run.

    Parameters
    ----------
    run_root : Path
        The run directory.

    Returns
    -------
    Path
    """
    return StateDirectoryManager.user_view_dir(run_root)


def steps_inside_run(run_root: Path, workplan: "LiveWorkplan") -> bool:
    """Whether every step of the transformed workplan lives inside the run directory.

    A workplan recorded on another machine, or before the run was moved, names
    step directories that this run directory does not contain.

    Parameters
    ----------
    run_root : Path
        The run directory.
    workplan : LiveWorkplan
        The run's transformed workplan.

    Returns
    -------
    bool
    """
    root = run_root.resolve()
    return all(s.working_dir.resolve().is_relative_to(root) for s in workplan.steps)


def _step_dirs(run_root: Path) -> "Iterator[Path]":
    """Yield each step directory under `run_root`, nested sub-steps included.

    A symlinked step directory is skipped, so a link back into the run cannot
    cause a cycle; it is reported with the other symlinks.

    Parameters
    ----------
    run_root : Path
        A resolved run or step directory.

    Yields
    ------
    Path
    """
    tasks_dir = JobFileSystemManager(run_root).tasks_dir
    if not tasks_dir.is_dir():
        return

    for entry in sorted(tasks_dir.iterdir()):
        if entry.is_dir() and not entry.is_symlink():
            yield entry
            yield from _step_dirs(entry)


def _prefixes(run_root: Path) -> tuple[Path, ...]:
    """The forms of the run directory a path written into a file may start with.

    The run directory as given and as resolved can differ when a parent is a
    symlink, as on data homes placed on a scratch file system.

    Parameters
    ----------
    run_root : Path
        The run directory as given.

    Returns
    -------
    tuple[Path, ...]
    """
    return tuple(dict.fromkeys((run_root, run_root.resolve())))


def _relative_to_prefix(text: str, prefixes: tuple[Path, ...]) -> Path | None:
    """Locate an absolute path text relative to the first prefix containing it.

    Parameters
    ----------
    text : str
        A symlink target.
    prefixes : tuple[Path, ...]
        The directories to try.

    Returns
    -------
    Path | None
        The path of `text` below the matching prefix, or `None` when `text` is
        relative or lies outside every prefix.
    """
    if not os.path.isabs(text):
        return None

    target = Path(os.path.normpath(text))
    return next(
        (target.relative_to(p) for p in prefixes if target.is_relative_to(p)), None
    )


def recorded_run_root(run_root: Path) -> Path | None:
    """The run root the run's transformed workplan recorded when it was written.

    It is read from the file as written: `LiveWorkplan.load` rebases it with
    the rest of the document.

    Parameters
    ----------
    run_root : Path
        The run directory.

    Returns
    -------
    Path | None
        `None` when the run has no readable transformed workplan, or one written
        before the root was recorded.
    """
    for path in sorted(run_root.glob(TRANSFORMED_WORKPLAN_GLOB)):
        try:
            recorded = read_document(path).get(LiveWorkplan.ROOT_FIELD)
        except Exception as ex:  # an unreadable workplan is reported by the caller
            log.debug("Unable to read the recorded root of %s: %s", path, ex)
            continue
        if isinstance(recorded, str) and os.path.isabs(recorded):
            return Path(recorded)

    return None


def is_run_path(text: str, run_root: Path, recorded_root: Path | None) -> bool:
    """Whether an absolute path names the run itself, wherever the run now is.

    A path inside the run directory, or inside the root the run's files were
    written under (the source of a copy), names the run's own files. The
    transformed workplan and the blueprints that hold such paths are rebased
    when they are read, so they keep working when the run is moved; a path
    anywhere else does not move with the run. A path spelled through a symlink
    to the run, as through a data home on a scratch file system, is resolved
    before it is compared.

    Parameters
    ----------
    text : str
        An absolute path found in a file of the run.
    run_root : Path
        The run directory as given.
    recorded_root : Path | None
        The run root the transformed workplan recorded (see `recorded_run_root`).

    Returns
    -------
    bool
    """
    roots = (run_root, *((recorded_root,) if recorded_root else ()))
    prefixes = tuple(dict.fromkeys(p for r in roots for p in _prefixes(r)))
    if _relative_to_prefix(text, prefixes) is not None:
        return True

    # the recorded root is resolved, while a file may name the run through an alias
    return _relative_to_prefix(os.path.realpath(text), prefixes) is not None


def _absolute_path_pattern(run_root: Path) -> re.Pattern[str]:
    """Compile the pattern matching an absolute path under the run or the data home.

    A path must start at its prefix, not at the tail of a longer path, and the
    prefix must end at a path-segment boundary, so that `/data/run-1` does not
    match `/data/run-10`.

    Parameters
    ----------
    run_root : Path
        The run directory as given.

    Returns
    -------
    re.Pattern[str]
    """
    home = DirectoryManager.data_home()
    prefixes = {str(p) for p in (*_prefixes(run_root), *_prefixes(home))}
    longest_first = sorted(prefixes, key=len, reverse=True)
    alternatives = "|".join(re.escape(p) for p in longest_first)
    return re.compile(rf"(?<![\w./~-])(?:{alternatives})(?![\w.-]){_PATH_CHARS_AFTER}")


def find_absolute_paths(run_root: Path, *, all_files: bool) -> list[Finding]:
    """Find absolute paths under the run, or the data home, in the files that describe it.

    Only the emitted files that refer to other files are scanned: each step's
    `output/*.yaml`, `blueprints/B_*.yaml` and `work/cstar_generated_roms.nml`,
    and the run's `*_transformed.yaml`. With `all_files`, the launch artifacts
    that launchers regenerate are scanned too. A path that names the run itself
    (see `is_run_path`) is a `RUN_PATH` finding, any other an `ABSOLUTE_PATH` one.

    Parameters
    ----------
    run_root : Path
        The run directory.
    all_files : bool
        Whether to scan the launch artifacts as well.

    Returns
    -------
    list[Finding]
        One `ABSOLUTE_PATH` or `RUN_PATH` finding per occurrence, ordered by
        file and line.
    """
    root = run_root.resolve()
    pattern = _absolute_path_pattern(run_root)
    recorded = recorded_run_root(root)
    globs = (*REFERENCE_FILES, *(LAUNCH_FILES if all_files else ()))

    candidates = [*root.glob(TRANSFORMED_WORKPLAN_GLOB)]
    for step_dir in _step_dirs(root):
        candidates.extend(p for g in globs for p in step_dir.glob(g))

    findings: list[Finding] = []
    for file in sorted({p for p in candidates if p.is_file()}):
        try:
            lines = file.read_text(errors="replace").splitlines()
        except OSError as ex:
            log.debug("Skipping unreadable file %s: %s", file, ex)
            continue

        for number, line in enumerate(lines, start=1):
            for match in pattern.finditer(line):
                text = match.group().rstrip(".:")
                kind = (
                    FindingKind.RUN_PATH
                    if is_run_path(text, run_root, recorded)
                    else FindingKind.ABSOLUTE_PATH
                )
                findings.append(Finding(kind, file, number, text))

    return findings


def find_bad_symlinks(run_root: Path) -> list[Finding]:
    """Find the symlinks under the run that stop working when the run is moved.

    A link is reported once: as dangling when its target does not exist, else as
    absolute when its target is an absolute path inside the run, or external when
    its target lies outside the run, as an absolute path or as a relative one that
    climbs out of it. A dangling link inside a step's cloned codebases is the
    codebase's own and is reported as such. Links are never followed, so a link
    into the run cannot cause a cycle.

    Parameters
    ----------
    run_root : Path
        The run directory.

    Returns
    -------
    list[Finding]
        `DANGLING_LINK`, `CODEBASE_LINK`, `ABSOLUTE_LINK` and `EXTERNAL_LINK`
        findings ordered by link.
    """
    root = run_root.resolve()
    prefixes = _prefixes(run_root)
    # a standalone blueprint run stages its codebases under the run root itself
    codebases = tuple(
        RomsFileSystemManager(d).codebases_dir for d in (root, *_step_dirs(root))
    )
    findings: list[Finding] = []

    for directory, dirnames, filenames in os.walk(root):
        for name in (*dirnames, *filenames):
            link = Path(directory, name)
            if not link.is_symlink():
                continue

            target = os.readlink(link)
            if not link.exists():
                kind = (
                    FindingKind.CODEBASE_LINK
                    if any(link.is_relative_to(c) for c in codebases)
                    else FindingKind.DANGLING_LINK
                )
            elif _relative_to_prefix(target, prefixes) is not None:
                kind = FindingKind.ABSOLUTE_LINK
            elif os.path.isabs(target) or not Path(
                os.path.normpath(Path(directory, target))
            ).is_relative_to(root):
                kind = FindingKind.EXTERNAL_LINK
            else:
                continue

            findings.append(Finding(kind, link, path=target))

    return sorted(findings, key=lambda f: f.file)


def find_missing_step_dirs(run_root: Path, workplan: "LiveWorkplan") -> list[Finding]:
    """Find the steps of the transformed workplan that have no directory in the run.

    The expected location is `tasks/<slug>` below the run directory rather than
    the step's recorded working directory, which names the machine the workplan
    was transformed on. A step that has not started yet has no directory either.

    Parameters
    ----------
    run_root : Path
        The run directory.
    workplan : LiveWorkplan
        The run's transformed workplan.

    Returns
    -------
    list[Finding]
        A `MISSING_STEP_DIR` finding per step, in workplan order.
    """
    tasks_dir = JobFileSystemManager(run_root).tasks_dir
    expected = (tasks_dir / step.safe_name for step in workplan.steps)
    return [
        Finding(FindingKind.MISSING_STEP_DIR, path)
        for path in expected
        if not path.is_dir()
    ]


def find_product_findings(
    run_root: Path,
    manifest: "RunManifest",
    *,
    verify: bool,
    tally: DigestTally | None = None,
) -> list[Finding]:
    """Compare the products the step records list with the run directory.

    Only the recorded products are looked at: the file system is not walked. A
    size of zero means the product was not measured, and is never compared. A log
    may still be written when the record is taken (the step's own output is), so
    only a log that shrank is reported.

    Parameters
    ----------
    run_root : Path
        The run directory.
    manifest : RunManifest
        The run's manifest, with the step records folded in.
    verify : bool
        Whether to compare the content of each product that records a digest (a
        record that predates digests has its sha256 folded into one). A netCDF
        file is read in part, as its digest was computed; any other file is read
        whole.
    tally : DigestTally | None
        With `verify`, each recorded product is counted here by what the
        comparison found: matched, differed, or why it was not compared.

    Returns
    -------
    list[Finding]
        `PRODUCT_MISSING`, `PRODUCT_SIZE` and `DIGEST_MISMATCH` findings in step and
        product order, `RECORD_MISSING` for each done step without a record, and
        `ATTEMPT_OPEN` when the latest attempt has not finished.
    """
    findings: list[Finding] = []
    counts = tally if tally is not None else DigestTally()

    for entry in manifest.steps:
        step_dir = run_root / entry.working_dir
        if entry.record is None:
            if entry.status == Status.Done.name:
                findings.append(
                    Finding(FindingKind.RECORD_MISSING, step_dir / STEP_RECORD_NAME)
                )
            continue

        for product in entry.record.products:
            file = step_dir / product.path
            # one stat per product: each call is a round trip on a parallel file system
            try:
                found = file.stat()
            except FileNotFoundError:
                findings.append(Finding(FindingKind.PRODUCT_MISSING, file))
                counts.not_compared += 1
                continue
            regular = stat.S_ISREG(found.st_mode)
            if product.known_kind is ArtifactKind.log:
                differs = found.st_size < product.size_bytes
            else:
                differs = found.st_size != product.size_bytes
            if product.size_bytes and regular and differs:
                text = f"{found.st_size} bytes, recorded {product.size_bytes}"
                findings.append(Finding(FindingKind.PRODUCT_SIZE, file, path=text))
                counts.not_compared += 1
            elif not verify:
                continue
            elif not regular:
                counts.not_compared += 1
            elif not (wanted := product.digest):
                counts.no_digest += 1
            elif (scheme := wanted.partition(":")[0]) not in KNOWN_SCHEMES:
                counts.foreign[scheme] = counts.foreign.get(scheme, 0) + 1
            else:
                try:
                    digest = product_digest(file, scheme=scheme)
                except Exception as ex:  # a file that cannot be read cannot be verified
                    digest = f"unreadable: {ex}"
                if digest == wanted:
                    counts.matched += 1
                else:
                    counts.differed += 1
                    findings.append(
                        Finding(FindingKind.DIGEST_MISMATCH, file, path=digest)
                    )

    if manifest.attempts and manifest.attempts[-1].finished_at is None:
        findings.append(Finding(FindingKind.ATTEMPT_OPEN, run_root / RUN_MANIFEST_NAME))

    return findings


def find_input_findings(run_root: Path, manifest: "RunManifest") -> list[Finding]:
    """Compare the inputs each attempt carried with the run directory.

    Only the files the manifest lists are read, and `attempts/` is not walked: a
    carried file is a workplan, variables or a blueprint, small by construction.
    An attempt directory that is gone is one finding, not one per file, since an
    older attempt may be deleted by hand. An attempt that carried nothing has no
    directory and nothing to compare.

    Parameters
    ----------
    run_root : Path
        The run directory.
    manifest : RunManifest
        The run's manifest.

    Returns
    -------
    list[Finding]
        `INPUT_MISSING` for each attempt directory, or carried file, that is not
        in the run, and `INPUT_MISMATCH` for each carried file whose content
        differs from the manifest, in attempt and file order.
    """
    findings: list[Finding] = []

    for attempt in manifest.attempts:
        if not attempt.directory:
            continue

        directory = run_root / attempt.directory
        if not directory.is_dir():
            findings.append(Finding(FindingKind.INPUT_MISSING, directory))
            continue

        for relative, digest in attempt.carried.items():
            file = directory / relative
            if not file.is_file():
                findings.append(Finding(FindingKind.INPUT_MISSING, file))
            elif (found := carried_digest(file)) != digest:
                findings.append(Finding(FindingKind.INPUT_MISMATCH, file, path=found))

    return findings


def orphan_task_dirs(run_root: Path, workplan: "LiveWorkplan") -> tuple[Path, ...]:
    """Find the entries of the run's `tasks` directory that no step accounts for.

    A directory is accounted for when a step works in it or in a directory
    nested beneath it, as the sub-steps of a split step do. Paths are compared
    resolved, so a run root reached through a symlink is still recognised.

    Parameters
    ----------
    run_root : Path
        The run directory.
    workplan : LiveWorkplan
        The run's transformed workplan.

    Returns
    -------
    tuple[Path, ...]
    """
    tasks_dir = JobFileSystemManager(run_root).tasks_dir
    if not tasks_dir.is_dir():
        return ()

    resolved_tasks = tasks_dir.resolve()
    claimed = {_task_dir_name(s.working_dir, resolved_tasks) for s in workplan.steps}
    return tuple(
        sorted(p for p in tasks_dir.iterdir() if p.is_dir() and p.name not in claimed)
    )


def _task_dir_name(working_dir: Path, tasks_dir: Path) -> str | None:
    """Return the name of the `tasks_dir` entry that holds `working_dir`.

    Parameters
    ----------
    working_dir : Path
        The directory a step works in; symlinks are resolved first.
    tasks_dir : Path
        An already-resolved `tasks` directory.

    Returns
    -------
    str | None
        `None` when the step works outside `tasks_dir`.
    """
    resolved = working_dir.resolve()
    if resolved == tasks_dir or not resolved.is_relative_to(tasks_dir):
        return None

    return resolved.relative_to(tasks_dir).parts[0]


def orphan_sentinels(run_id: str, workplan: "LiveWorkplan") -> tuple[Path, ...]:
    """Find the sentinel files of a run that match no step's expected sentinel name.

    Sentinels live in the run's state directory, keyed by run-id, not inside the
    run directory.

    Parameters
    ----------
    run_id : str
        The run-id the sentinels were written under.
    workplan : LiveWorkplan
        The run's transformed workplan.

    Returns
    -------
    tuple[Path, ...]
    """
    state_dir = StateDirectoryManager.run_state_dir(run_id=run_id)
    expected = {
        StateRepository.sentinel_path(step.safe_name, run_id=run_id).name
        for step in workplan.steps
    }
    found = state_dir.rglob(StateRepository.sentinel_name("*"))
    return tuple(sorted(p for p in found if p.name not in expected))


def find_orphans(run_root: Path, run_id: str, workplan: "LiveWorkplan") -> Orphans:
    """Find the task directories and sentinel files that no step accounts for.

    Parameters
    ----------
    run_root : Path
        The run directory.
    run_id : str
        The run-id whose sentinel files are examined.
    workplan : LiveWorkplan
        The run's transformed workplan.

    Returns
    -------
    Orphans
    """
    return Orphans(
        step_dirs=orphan_task_dirs(run_root, workplan),
        sentinels=orphan_sentinels(run_id, workplan),
    )


def report_orphans(run_root: Path, run_id: str, workplan: "LiveWorkplan") -> Orphans:
    """Log one warning listing the orphans of a run that is being re-entered.

    Parameters
    ----------
    run_root : Path
        The run's directory.
    run_id : str
        The run-id.
    workplan : LiveWorkplan
        The prepared workplan the run executes.

    Returns
    -------
    Orphans
        What was found, which is empty when nothing was reported.
    """
    orphans = find_orphans(run_root, run_id, workplan)
    if orphans:
        listed = [
            f"{label}: {', '.join(str(p) for p in paths)}"
            for label, paths in (
                ("step directories", orphans.step_dirs),
                ("state files", orphans.sentinels),
            )
            if paths
        ]
        msg = (
            f"Run {run_id!r} holds items that no step of its workplan accounts "
            f"for ({'; '.join(listed)}). They were left in place; remove them "
            "by hand once you have confirmed they are not needed."
        )
        log.warning(msg)

    return orphans


def repair_symlinks(run_root: Path) -> list[Path]:
    """Rewrite each absolute symlink that points inside the run as a relative one.

    Only `ABSOLUTE_LINK` findings are touched: links whose target exists and lies
    inside the run. Dangling links and links leaving the run are left as they
    are. Each link is replaced atomically, so it never disappears mid-repair.

    Parameters
    ----------
    run_root : Path
        The run directory.

    Returns
    -------
    list[Path]
        The links that were rewritten.
    """
    root = run_root.resolve()
    prefixes = _prefixes(run_root)
    repaired: list[Path] = []

    for finding in find_bad_symlinks(run_root):
        below_root = _relative_to_prefix(finding.path, prefixes)
        if finding.kind is not FindingKind.ABSOLUTE_LINK or below_root is None:
            continue

        # the target is rebased onto the resolved root the link was found under,
        # so the relative text cannot climb out of the run and back in again
        staged = finding.file.with_name(f".{finding.file.name}.{os.getpid()}.repair")
        symlink_relative(staged, root / below_root)
        staged.replace(finding.file)
        repaired.append(finding.file)

    return repaired


def check_run(
    run_root: Path,
    *,
    workplan: "LiveWorkplan | None",
    run_id: str | None,
    all_files: bool,
    manifest: "RunManifest | None" = None,
    verify: bool = False,
) -> RunCheckReport:
    """Run every check that applies to a run directory.

    The step and orphan checks need the transformed workplan, and the sentinel
    check needs the run-id too: one is only trustworthy when the run was found
    through tracking. The product checks need the run's manifest, with the step
    records folded in, and so do the carried-input checks, which are not gated by
    `verify`: the files they read are small. A check that cannot run is named in
    `skipped`; with `verify`, what the comparison found is in `verification`.

    Parameters
    ----------
    run_root : Path
        The run directory.
    workplan : LiveWorkplan | None
        The run's transformed workplan, when it could be loaded.
    run_id : str | None
        The run-id, when the run was found through tracking.
    all_files : bool
        Whether to scan the launch artifacts for absolute paths too.
    manifest : RunManifest | None
        The run's manifest, when it could be read.
    verify : bool
        Whether to compare the content of products that record a digest.

    Returns
    -------
    RunCheckReport
    """
    # the root is passed as given: a path written through a symlinked parent of
    # the run is only recognized as the run's when that spelling is known
    findings = [
        *find_absolute_paths(run_root, all_files=all_files),
        *find_bad_symlinks(run_root),
    ]
    orphans = Orphans()
    skipped: list[str] = []
    tally = DigestTally() if verify and manifest is not None else None

    if workplan is None:
        skipped.append("step directories and orphans: no transformed workplan")
    else:
        findings.extend(find_missing_step_dirs(run_root, workplan))
        if run_id is None:
            orphans = Orphans(step_dirs=orphan_task_dirs(run_root, workplan))
            skipped.append(
                "orphaned sentinels: sentinel files live in the state home under "
                "a tracked run's run-id, so a run checked by its directory has none"
            )
        else:
            orphans = find_orphans(run_root, run_id, workplan)

    if manifest is None:
        skipped.append("products and carried inputs: no run manifest")
    else:
        findings.extend(
            find_product_findings(run_root, manifest, verify=verify, tally=tally)
        )
        findings.extend(find_input_findings(run_root, manifest))

    order = {kind: i for i, kind in enumerate(FindingKind)}
    findings.sort(key=lambda f: (order[f.kind], f.file, f.line or 0))
    return RunCheckReport(
        run_root.resolve(), tuple(findings), orphans, tuple(skipped), tally
    )
